#!/usr/bin/env node
/**
 * Writes the Nx version plan of the next release: one `<component>: <bump>` line per component whose own
 * directories received a commit of a releasing type (R6) since its last `<component>/<version>` tag.
 * `nx release version` reads the plan (specifierSource "version-plans") and gives every in-repo dependent
 * of a bumped component a patch bump itself.
 *
 * WHY NX ALONE IS NOT ENOUGH
 *
 * With specifierSource "conventional-commits", Nx 23 decides which commits belong to a project with the
 * `nx affected` logic, which adds every transitive dependent of the files a commit touches. A `feat!` in
 * api-unifier then counts as a breaking commit of api-diff, api-processor, ui, and build-task-consumer,
 * which all go major, although R6 gives a component released only because of a dependency a patch bump.
 * The imported histories make it worse: a library's commits that are not ancestors of a dependent's tag,
 * such as api-processor's long-released `feat!`, fall into the dependent's range. No Nx option changes
 * this (useCommitScope only downgrades commits scoped to another project). So the bump of each component
 * is computed here from `git log --no-merges <last tag>..HEAD -- <component directories>`, the rule of the
 * release design, and Nx only applies it. See monorepo_migration R0 spike report for the measurements.
 *
 * Usage: node tools/release/version-plan.js   writes .nx/version-plans/release.md, or removes it when
 *                                             nothing is to be released, and prints the bumps
 */
const fs = require('node:fs')
const path = require('node:path')
const { WORKSPACE_ROOT, bumpFromCommits, commitTypes, compareSemver, listTags, parseSemver, readNxRelease } =
  require('./conventional')

const PLAN_FILE = path.join(WORKSPACE_ROOT, '.nx', 'version-plans', 'release.md')

/** Pathspecs of a component: its project roots, minus the roots of nested projects of other components. */
function componentPaths(groupProjects, allRoots) {
  const own = new Set(groupProjects)
  const roots = [...new Set(groupProjects.map((p) => allRoots[p]))].filter(
    (r, _, all) => !all.some((o) => o !== r && r.startsWith(o + '/')),
  )
  const excluded = Object.entries(allRoots)
    .filter(([p, r]) => !own.has(p) && roots.some((root) => r !== root && r.startsWith(root + '/')))
    .map(([, r]) => `:(exclude)${r}`)
  return [...roots, ...excluded]
}

/** The tag Nx resolves the current version from: the highest stable version matching the group's pattern. */
function lastReleaseTag(component, group, release, tags) {
  const pattern = (group.releaseTag?.pattern ?? release.releaseTag.pattern).replace('{releaseGroupName}', component)
  const [prefix, suffix] = pattern.split('{version}')
  const versions = tags
    .filter((t) => t.startsWith(prefix) && t.endsWith(suffix))
    .map((t) => t.slice(prefix.length, t.length - suffix.length))
    .filter((v) => parseSemver(v)?.pre === '')
  const last = versions.sort(compareSemver).at(-1)
  return last ? `${prefix}${last}${suffix}` : null
}

/**
 * `[{ component, lastTag, bump }]` for every release group, in nx.json order.
 * `bumpOf(lastTag, paths)` gives the highest R6 bump among the commits since `lastTag` that touch `paths`.
 */
function componentBumps({ release, roots, tags, bumpOf }) {
  return Object.entries(release.groups).map(([component, group]) => {
    const lastTag = lastReleaseTag(component, group, release, tags)
    return { component, lastTag, bump: bumpOf(lastTag, componentPaths(group.projects, roots)) }
  })
}

function renderVersionPlan(bumps) {
  const lines = bumps.filter((b) => b.bump !== 'none').map((b) => `${b.component}: ${b.bump}`)
  if (!lines.length) return null
  return ['---', ...lines, '---', '', 'Generated by tools/release/version-plan.js; never committed.', ''].join('\n')
}

async function projectRoots() {
  const { createProjectGraphAsync } = require('nx/src/devkit-exports')
  const graph = await createProjectGraphAsync({ exitOnError: true })
  return Object.fromEntries(Object.values(graph.nodes).map((n) => [n.name, n.data.root.replace(/\\/g, '/')]))
}

/** Computes the bumps, writes or removes the plan file, and returns the bumps. */
async function writeVersionPlan(file = PLAN_FILE) {
  const release = readNxRelease()
  const types = commitTypes(release)
  const bumps = componentBumps({
    release,
    roots: await projectRoots(),
    tags: listTags(),
    bumpOf: (lastTag, paths) => bumpFromCommits(lastTag, paths, types),
  })
  const plan = renderVersionPlan(bumps)
  if (plan) {
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.writeFileSync(file, plan)
  } else {
    fs.rmSync(file, { force: true })
  }
  return bumps
}

if (require.main === module) {
  writeVersionPlan()
    .then((bumps) => {
      for (const b of bumps) {
        console.log(`${b.component.padEnd(36)} ${b.bump.padEnd(6)} since ${b.lastTag ?? 'the start'}`)
      }
      const n = bumps.filter((b) => b.bump !== 'none').length
      const file = path.relative(WORKSPACE_ROOT, PLAN_FILE)
      console.log(n ? `version plan: ${file} (${n} components)` : 'nothing to release')
    })
    .catch((e) => {
      process.stderr.write(`version-plan: ${e.stack || e}\n`)
      process.exit(1)
    })
}

module.exports = { PLAN_FILE, componentBumps, componentPaths, lastReleaseTag, renderVersionPlan, writeVersionPlan }
