/** `[wait import, wait call]` per API type and plain / diffs. */
const VIEWER_WAITS = {
  "JSON Schema": [["waitForJsonSchemaViewer", "waitForJsonSchemaViewer(page)"], ["waitForJsonSchemaDiffsViewer", "waitForJsonSchemaDiffsViewer(page)"]],
  "AsyncAPI": [["waitForRenderingComplete", "waitForRenderingComplete(page)"], ["waitForRenderingComplete", "waitForRenderingComplete(page)"]],
  "OpenAPI": [["waitForOpenApiOperationViewer", "waitForOpenApiOperationViewer(page)"], ["waitForOpenApiOperationDiffsViewer", "waitForOpenApiOperationDiffsViewer(page)"]],
  "DDL API": [["waitForDdlTableViewer", "waitForDdlTableViewer(page)"], ["waitForDdlTableDiffsViewer", "waitForDdlTableDiffsViewer(page)"]],
};

function writeTests(suite, cases) {
  const isAsyncApi = suite.apiTitle === "AsyncAPI";
  const [waitName, waitCall] = VIEWER_WAITS[suite.apiTitle][suite.diffs ? 1 : 0];
  const rows = cases.map((definition) => {
    const section = definition.section ? `'${ASYNC_API_SECTION_TEST_IDS[definition.section]}'` : "undefined";
    return isAsyncApi
      ? `  ['${definition.caseId}', '${storyIdOf(suite, definition.caseId)}', ${section}],`
      : `  ['${definition.caseId}', '${storyIdOf(suite, definition.caseId)}'],`;
  });
  const casesType = isAsyncApi
    ? `/** [case id, story id, message section tab opened before the capture]. */
const CASES: ReadonlyArray<readonly [string, string, string | undefined]> = [`
    : `/** [case id, story id]. */
const CASES: ReadonlyArray<readonly [string, string]> = [`;
  const body = isAsyncApi
    ? `    it.each(CASES)('%s', async (_caseId, storyId, section) => {
      const story = await storyPageWithArgs(page, storyId, { displayMode })
      const component = await story.viewComponent()
      await waitForRenderingComplete(page)
      if (section) {
        await page.click(\`[data-testid="\${section}"]\`)
        await page.waitForSelector(\`[data-testid="\${section}-section"]\`, { visible: true })
        await waitForRenderingComplete(page)
      }
      expect(await component.captureScreenshot()).toMatchImageSnapshot()
    })`
    : `    it.each(CASES)('%s', async (_caseId, storyId) => {
      const story = await storyPageWithArgs(page, storyId, { displayMode })
      const component = await story.viewComponent()
      await ${waitCall}
      expect(await component.captureScreenshot()).toMatchImageSnapshot()
    })`;
  const text = `// ${GENERATED}
/**
 * Screenshot tests for ${suite.title}:
 * every case in display modes \`detailed\` and \`simple\` (the same story, \`displayMode\` passed as a
 * story arg) - the only \`simple\` coverage of ${suite.apiTitle}.
 */
import { storyPageWithArgs } from '../service/storybook-service'
import { ${waitName} } from '../service/viewer-waits'

${casesType}
${rows.join("\n")}
]

describe('${suite.title}', () => {
  beforeEach(async () => {
    await jestPuppeteer.resetPage()
  })

  describe.each(['detailed', 'simple'])('display mode %s', (displayMode) => {
${body}
  })
})
`;
  const itDir = path.join(packageRoot, "src/it", testRunOf(suite));
  fs.mkdirSync(itDir, { recursive: true });
  // Only the ITs: the folder also holds the committed baselines (`__image_snapshots__/`).
  for (const file of fs.readdirSync(itDir)) {
    if (file.endsWith(".it-test.ts")) {
      fs.rmSync(path.join(itDir, file));
    }
  }
  fs.writeFileSync(path.join(itDir, TESTS_FILE), text, "utf8");
}

function writeStories(suite, cases) {
  const printer = STORY_PRINTERS[suite.apiTitle][suite.diffs ? 1 : 0];
  const storiesDir = path.join(packageRoot, "src/stories", testRunOf(suite));
  fs.rmSync(storiesDir, { recursive: true, force: true });
  fs.mkdirSync(storiesDir, { recursive: true });
  fs.writeFileSync(path.join(storiesDir, STORIES_FILE), `// ${GENERATED}\n${printer(suite, cases)}`, "utf8");
}

function main() {
  for (const suite of SUITES) {
    const cases = expandCases(suite);
    writeFixtures(suite, cases);
    writeCatalogue(suite, cases);
    writeStories(suite, cases);
    writeTests(suite, cases);
    console.log(`${suite.title}: ${cases.length} cases (${testRunOf(suite)}).`);
  }
}

main();
