/**
 * Generates the display-mode suites from `bin/display-mode-simple-case-definitions.mjs`: for AsyncAPI,
 * OpenAPI, JSON Schema, and DDL API, one plain `* Suite (Display Mode = simple)` and one
 * `* Diffs Suite (Display Mode = simple)`. Per suite (test run `<samples folder>-suite`):
 *
 * - fixtures and catalogue: `packages/samples/<samples folder>/` (recreated as a whole), one minimal
 *   document (plain: `sample.<ext>`; diffs: `before.<ext>` / `after.<ext>`) per element `simple` hides;
 * - stories: `src/stories/<test run>/cases.stories.tsx` (one story per case; `displayMode` is a story
 *   control, default `detailed`);
 * - screenshot ITs: `src/it/<test run>/cases.it-test.ts`, every case in display modes `detailed` and
 *   `simple` (the same story, `displayMode` passed as a story arg). Baselines:
 *   `src/it/<test run>/__image_snapshots__/` (kept on regeneration).
 *
 * Every other suite captures `detailed` only; these suites are the only `simple` coverage.
 * Design: docs/design/shared/features/display-mode-annotations.md.
 *
 * Usage (from packages/api-doc-viewer): node bin/generate-display-mode-simple-suites.mjs
 */
