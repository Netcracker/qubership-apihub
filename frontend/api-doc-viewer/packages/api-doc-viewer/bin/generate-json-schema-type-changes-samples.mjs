import { mkdirSync, rmSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { stringify as stringifyYaml } from "yaml";
import { exitIfInsideNodeModules } from "./compatibility-suite-generation-utils.mjs";
import {
  STORY_SUITES,
  collectTypeChangeCases,
  toExportName,
} from "./json-schema-type-changes-cases.mjs";
import { spawnSync } from "child_process";
import {
  toStorybookMetaId,
  toStorybookStorySlug,
} from "./storybook-story-id-utils.mjs";

const testsOnly = process.argv.includes("--tests-only");

exitIfInsideNodeModules(import.meta.url);

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(__dirname, "..");
const samplesRoot = path.resolve(packageRoot, "../samples/json-schema-diffs/type-changes");
const storiesOutDir = path.resolve(packageRoot, "src/stories/json-schema-diffs-suite");
const testsOutDir = path.resolve(packageRoot, "src/it/json-schema-diffs-suite");

const serializeSchema = (schema) => `${stringifyYaml(schema, { lineWidth: 0 })}\n`;

// Suites normally own their whole `globPath` directory 1:1. `caseFilter` lets two suites share one
// glob path (e.g. an OAS-3.1-only sibling suite for a keyword the default OAS-3.0 preprocessing
// pipeline can't carry through `apiDiff`'s `validate: true`) - default (no filter) keeps every
// case in that directory, matching prior behavior for every suite that doesn't opt in.
const matchesSuite = (suite, sampleCase) =>
  sampleCase.sampleDir === suite.globPath && (!suite.caseFilter || suite.caseFilter(sampleCase.caseId));

const writeSampleCase = (sampleCase) => {
  const caseDir = path.join(samplesRoot, sampleCase.sampleDir, sampleCase.caseId);
  mkdirSync(caseDir, { recursive: true });
  writeFileSync(path.join(caseDir, "before.yaml"), serializeSchema(sampleCase.before));
  writeFileSync(path.join(caseDir, "after.yaml"), serializeSchema(sampleCase.after));
};

const printStoryFile = (suite, suiteCases) => {
  const exports = suiteCases
    .map(({ caseId, displayName }) => {
      const factoryCall = `createCaseStory("${caseId}")`;
      return displayName
        ? `export const ${toExportName(caseId)}: Story = { ...${factoryCall}, name: ${JSON.stringify(displayName)} };`
        : `export const ${toExportName(caseId)}: Story = ${factoryCall};`;
    })
    .join("\n");
  // Story component rendering one case (default: plain OAS 3.0 merge). Suites needing another
  // merge pipeline pick a sibling export of json-schema-diffs-utils.tsx, or a suite-specific
  // module via `storyComponentModule` (e.g. circular fixtures with their own YAML shape).
  const storyComponent = suite.storyComponent ?? "JsonSchemaDiffSamplesStory";
  const storyComponentImport = suite.storyComponentModule
    ? `import { ${storyComponent} } from "${suite.storyComponentModule}";\n`
    : "";
  const sharedStoryComponentImport = suite.storyComponentModule ? "" : `  ${storyComponent},\n`;

  return `/**
 * Generated by packages/api-doc-viewer/bin/generate-json-schema-type-changes-samples.mjs
 * Fixtures: packages/samples/json-schema-diffs/type-changes/${suite.globPath}/
 */
import type { Meta, StoryObj } from "@storybook/react-vite";
import { collectSampleCases } from "../utils/diffs-samples-cases";
${storyComponentImport}import {
${sharedStoryComponentImport}  createJsonSchemaDiffCaseStoryFactoryWithChangedVariant,
  jsonSchemaDiffSampleReadonlyArgTypes,
} from "./json-schema-diffs-utils";
import { createSampleById } from "../utils/sample-cases";

const beforeFiles = import.meta.glob(
  "../../../../samples/json-schema-diffs/type-changes/${suite.globPath}/*/before.yaml",
  { query: "?raw", import: "default", eager: true },
) as Record<string, string>;

const afterFiles = import.meta.glob(
  "../../../../samples/json-schema-diffs/type-changes/${suite.globPath}/*/after.yaml",
  { query: "?raw", import: "default", eager: true },
) as Record<string, string>;

const sampleCases = collectSampleCases(beforeFiles, afterFiles);
const sampleById = createSampleById(sampleCases);

// eslint-disable-next-line storybook/story-exports
const meta = {
  title: "${suite.title}",
  component: ${storyComponent},
  argTypes: jsonSchemaDiffSampleReadonlyArgTypes,
} satisfies Meta<typeof ${storyComponent}>;

export default meta;

type Story = StoryObj<typeof meta>;

const createCaseStory = createJsonSchemaDiffCaseStoryFactoryWithChangedVariant(
  ${storyComponent},
  sampleById,
);

${exports}
`;
};

const printTestFile = (suite, caseIds) => {
  const metaId = toStorybookMetaId(suite.title);
  const tests = caseIds
    .map(
      (caseId) => {
        const storySlug = toStorybookStorySlug(toExportName(caseId));
        return `
  it("${caseId}", async () => {
    story = await storyPage(page, \`${metaId}--${storySlug}\`);
    await waitForJsonSchemaDiffsViewer(page, { switchCombinerVariant: true });
    component = await story.viewComponent();
    expect(await component.captureScreenshot()).toMatchImageSnapshot();
  });`;
      },
    )
    .join("\n");

  return `/**
 * Generated by packages/api-doc-viewer/bin/generate-json-schema-type-changes-samples.mjs
 * Edit together with src/stories/json-schema-diffs-suite/${suite.storyFileName}
 */
import { StoryPage } from "../service/story-page";
import { ViewComponent } from "../service/view-component";
import { storyPage } from "../service/storybook-service";
import { waitForJsonSchemaDiffsViewer } from "../service/viewer-waits";

const META_ID = "${metaId}";

describe("${suite.title}", () => {
  let story: StoryPage;
  let component: ViewComponent;

  beforeEach(async () => {
    await jestPuppeteer.resetPage();
  });
${tests}
});
`;
};

const buildReadme = (cases) => {
  const lines = [
    "# JSON Schema diff fixtures — type changes",
    "",
    "Hand-written YAML pairs (generated from case definitions) for the **JSON Schema Diffs Suite**",
    "Storybook group. Each case directory contains `before.yaml` and `after.yaml` as standalone",
    "JSON Schema documents.",
    "",
    `- Total cases: ${cases.length}`,
    "- Generator: `packages/api-doc-viewer/bin/generate-json-schema-type-changes-samples.mjs`",
    "",
    "## Cases",
    "",
  ];

  for (const suite of STORY_SUITES) {
    const suiteCases = cases.filter((sampleCase) => matchesSuite(suite, sampleCase));
    lines.push(`### ${suite.title.replace("JSON Schema Diffs Suite/", "")}`, "");
    lines.push(`Path: \`type-changes/${suite.globPath}/\` (${suiteCases.length} cases)`, "");
    lines.push("| Case id | Change |");
    lines.push("| --- | --- |");
    for (const sampleCase of suiteCases) {
      lines.push(`| \`${sampleCase.caseId}\` | ${sampleCase.summary} |`);
    }
    lines.push("");
  }

  lines.push(
    "## Storybook and screenshot tests",
    "",
    "Stories live under `packages/api-doc-viewer/src/stories/json-schema-diffs-suite/`.",
    "Screenshot ITs live under `packages/api-doc-viewer/src/it/json-schema-diffs-suite/`.",
    "",
    "## Regenerate",
    "",
    "```bash",
    "cd packages/api-doc-viewer",
    "node bin/generate-json-schema-type-changes-samples.mjs",
    "npm run build:showcase",
    "npm run regenerate-screenshots -- --testPathPattern=type-changes",
    "```",
    "",
  );

  return `${lines.join("\n")}\n`;
};

mkdirSync(storiesOutDir, { recursive: true });
mkdirSync(testsOutDir, { recursive: true });

const cases = collectTypeChangeCases();

if (!testsOnly) {
  rmSync(samplesRoot, { recursive: true, force: true });
  mkdirSync(samplesRoot, { recursive: true });

  for (const sampleCase of cases) {
    writeSampleCase(sampleCase);
  }

  writeFileSync(
    path.join(samplesRoot, "manifest.json"),
    `${JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        totalCases: cases.length,
        suites: STORY_SUITES.map((suite) => ({
          globPath: suite.globPath,
          caseCount: cases.filter((sampleCase) => matchesSuite(suite, sampleCase)).length,
        })),
      },
      null,
      2,
    )}\n`,
  );

  writeFileSync(path.join(samplesRoot, "README.md"), buildReadme(cases));
}

for (const suite of STORY_SUITES) {
  const suiteCases = cases
    .filter((sampleCase) => matchesSuite(suite, sampleCase))
    .sort((left, right) => left.caseId.localeCompare(right.caseId, undefined, { numeric: true }));
  const caseIds = suiteCases.map((sampleCase) => sampleCase.caseId);

  const storyPath = path.join(storiesOutDir, suite.storyFileName);
  const testPath = path.join(testsOutDir, suite.testFileName);
  if (!testsOnly) {
    writeFileSync(storyPath, printStoryFile(suite, suiteCases));
  }
  writeFileSync(testPath, printTestFile(suite, caseIds));
  console.log(`Generated ${caseIds.length} ${testsOnly ? "tests" : "cases"} -> ${suite.testFileName}`);
}

if (!testsOnly) {
  console.log(`Wrote ${cases.length} sample pairs under ${samplesRoot}`);

  const valueRangeStoriesScript = path.join(__dirname, "generate-value-range-diff-stories.mjs");
  const valueRangeResult = spawnSync(
    process.execPath,
    ["--experimental-strip-types", valueRangeStoriesScript],
    {
      cwd: packageRoot,
      stdio: "inherit",
    },
  );
  if (valueRangeResult.status !== 0) {
    process.exit(valueRangeResult.status ?? 1);
  }
}
