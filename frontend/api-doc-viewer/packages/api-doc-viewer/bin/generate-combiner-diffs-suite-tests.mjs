import { mkdirSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { exitIfInsideNodeModules } from "./compatibility-suite-generation-utils.mjs";
import { COMBINER_KINDS, combinerKindLabel, combinerKindSlug } from "./combiner-schema-builder.mjs";
import { listCombinerDiffCases } from "./combiner-diff-case-definitions.mjs";
import { toStorybookMetaId } from "./storybook-story-id-utils.mjs";

exitIfInsideNodeModules(import.meta.url);

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(__dirname, "..");
const testsOutDir = path.resolve(packageRoot, "src/it/json-schema-diffs-suite");

/** @type {Array<{ combinerKind: string, storyFileName: string, testFileName: string, metaKebab: string, title: string }>} */
const COMBINER_DIFF_STORY_SUITES = COMBINER_KINDS.map((combinerKind) => {
  const slug = combinerKindSlug(combinerKind);
  const label = combinerKindLabel(combinerKind);
  const title = `JSON Schema Diffs Suite/Combiners/${label} Combiner Diffs Suite`;
  return {
    combinerKind,
    storyFileName: `${slug}-combiner-diffs-suite.stories.tsx`,
    testFileName: `${slug}-combiner-diffs-suite.it-test.ts`,
    metaKebab: toStorybookMetaId(title),
    title,
  };
});

mkdirSync(testsOutDir, { recursive: true });

/**
 * @param {typeof COMBINER_DIFF_STORY_SUITES[number]} suite
 * @param {ReturnType<typeof listCombinerDiffCases>} cases
 */
const printTestFile = (suite, cases) => {
  // allOf has no variant selector (all sub-schemas apply simultaneously) -- nothing to switch.
  const includesChangedVariantSwitch = suite.combinerKind !== "allOf";
  const waitOptions = includesChangedVariantSwitch ? ", { switchCombinerVariant: true }" : "";
  const tests = cases
    .map(
      (sampleCase) => `
  it("${sampleCase.caseId}", async () => {
    story = await storyPage(page, \`${suite.metaKebab}--case-${sampleCase.caseId}\`);
    await waitForJsonSchemaDiffsViewer(page${waitOptions});
    component = await story.viewComponent();
    expect(await component.captureScreenshot()).toMatchImageSnapshot();
  });`,
    )
    .join("\n");

  return `/**
 * Generated by packages/api-doc-viewer/bin/generate-combiner-diffs-suite-tests.mjs
 * Edit together with src/stories/json-schema-diffs-suite/${suite.storyFileName}
 */
import { StoryPage } from "../service/story-page";
import { ViewComponent } from "../service/view-component";
import { storyPage } from "../service/storybook-service";
import { waitForJsonSchemaDiffsViewer } from "../service/viewer-waits";

const META_ID = "${suite.metaKebab}";

describe("${suite.title}", () => {
  let story: StoryPage;
  let component: ViewComponent;

  beforeEach(async () => {
    await jestPuppeteer.resetPage();
  });
${tests}
});
`;
};

for (const suite of COMBINER_DIFF_STORY_SUITES) {
  const cases = listCombinerDiffCases(suite.combinerKind);
  const filePath = path.join(testsOutDir, suite.testFileName);
  writeFileSync(filePath, printTestFile(suite, cases));
  console.log(`Generated ${path.relative(packageRoot, filePath)} (${cases.length} cases)`);
}
