/**
 * Generates the "JSON Schema Diffs Suite/Property Rename" stories and screenshot ITs from the
 * OpenAPI fixture pairs under packages/samples/json-schema-diffs/property-rename/<case-id>/.
 *
 * Usage (from packages/api-doc-viewer): node bin/generate-json-schema-property-rename-suite.mjs
 *
 * Output is committed. Do not add this generator to the `generate-stories` / `generate-tests`
 * npm scripts (compatibility suite only).
 */
import { existsSync, readdirSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { exitIfInsideNodeModules } from "./compatibility-suite-generation-utils.mjs";
import { toStorybookMetaId, toStorybookStorySlug } from "./storybook-story-id-utils.mjs";

exitIfInsideNodeModules(import.meta.url);

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(__dirname, "..");
const samplesDir = path.resolve(packageRoot, "../samples/json-schema-diffs/property-rename");
const storyFile = path.resolve(packageRoot, "src/stories/json-schema-diffs-suite/property-rename.stories.tsx");
const testFile = path.resolve(packageRoot, "src/it/json-schema-diffs-suite/property-rename.it-test.ts");

const TITLE = "JSON Schema Diffs Suite/Property Rename";
const GENERATED_BY = "packages/api-doc-viewer/bin/generate-json-schema-property-rename-suite.mjs";

const collectCaseIds = () =>
  readdirSync(samplesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((caseId) =>
      existsSync(path.join(samplesDir, caseId, "before.yaml"))
      && existsSync(path.join(samplesDir, caseId, "after.yaml")),
    )
    .sort((left, right) => left.localeCompare(right, undefined, { numeric: true }));

const toExportName = (caseId) => `Case_${caseId.replaceAll(/[^A-Za-z0-9]+/g, "_")}`;

const printStoryFile = (caseIds) => `/**
 * Generated by ${GENERATED_BY}
 * Edit together with src/it/json-schema-diffs-suite/property-rename.it-test.ts
 */
import { JsonSchemaDiffsViewer } from "@apihub/components/JsonSchemaViewer/JsonSchemaDiffsViewer";
import type { Meta, StoryObj } from "@storybook/react-vite";
import { collectSampleCases } from "../utils/diffs-samples-cases";
import { createSampleById } from "../utils/sample-cases";
import {
  createJsonSchemaDiffCaseStoryFactory,
  JSON_SCHEMA_DIFF_META_KEYS,
  JSON_SCHEMA_DIFFS_SUITE_EXPANDED_DEPTH,
  type JsonSchemaDiffCaseStoryComponentProps,
  jsonSchemaDiffSampleReadonlyArgTypes,
} from "./json-schema-diffs-utils";
import { createParametersSchemaFromOpenApiPair } from "./parameters-schema-synthesis";

/**
 * Fixtures are OpenAPI documents, not JSON Schemas: \`apiDiff\` never renames a JSON Schema property,
 * so the viewer gets a schema synthesized from the operation's parameters, where a renamed path
 * parameter becomes a \`rename\` of its property key (see \`parameters-schema-synthesis.ts\`).
 */
const beforeFiles = import.meta.glob(
  "../../../../samples/json-schema-diffs/property-rename/*/before.yaml",
  { query: "?raw", import: "default", eager: true },
) as Record<string, string>;

const afterFiles = import.meta.glob(
  "../../../../samples/json-schema-diffs/property-rename/*/after.yaml",
  { query: "?raw", import: "default", eager: true },
) as Record<string, string>;

const sampleById = createSampleById(collectSampleCases(beforeFiles, afterFiles));

const PropertyRenameDiffsStory = ({ beforeYaml, afterYaml, hideUnchangedNodes }: JsonSchemaDiffCaseStoryComponentProps) => (
  <JsonSchemaDiffsViewer
    schema={createParametersSchemaFromOpenApiPair(beforeYaml, afterYaml)}
    expandedDepth={JSON_SCHEMA_DIFFS_SUITE_EXPANDED_DEPTH}
    diffMetaKeys={JSON_SCHEMA_DIFF_META_KEYS}
    hideUnchangedNodes={hideUnchangedNodes}
  />
);

// eslint-disable-next-line storybook/story-exports
const meta = {
  title: "${TITLE}",
  component: PropertyRenameDiffsStory,
  argTypes: jsonSchemaDiffSampleReadonlyArgTypes,
} satisfies Meta<typeof PropertyRenameDiffsStory>;

export default meta;

type Story = StoryObj<typeof meta>;

const createCaseStory = createJsonSchemaDiffCaseStoryFactory(PropertyRenameDiffsStory, sampleById);

${caseIds.map((caseId) => `export const ${toExportName(caseId)}: Story = createCaseStory("${caseId}");`).join("\n")}
`;

const printTestFile = (caseIds) => `/**
 * Generated by ${GENERATED_BY}
 * Edit together with src/stories/json-schema-diffs-suite/property-rename.stories.tsx
 */
import { StoryPage } from "../service/story-page";
import { ViewComponent } from "../service/view-component";
import { storyPage } from "../service/storybook-service";
import { waitForJsonSchemaDiffsViewer } from "../service/viewer-waits";

const META_ID = "${toStorybookMetaId(TITLE)}";

describe("${TITLE}", () => {
  let story: StoryPage;
  let component: ViewComponent;

  beforeEach(async () => {
    await jestPuppeteer.resetPage();
  });
${caseIds.map((caseId) => `
  it("${caseId}", async () => {
    story = await storyPage(page, \`\${META_ID}--${toStorybookStorySlug(toExportName(caseId))}\`);
    await waitForJsonSchemaDiffsViewer(page);
    component = await story.viewComponent();
    expect(await component.captureScreenshot()).toMatchImageSnapshot();
  });
`).join("")}});
`;

const caseIds = collectCaseIds();
writeFileSync(storyFile, printStoryFile(caseIds));
writeFileSync(testFile, printTestFile(caseIds));
console.log(`[property-rename] ${caseIds.length} cases -> ${path.relative(packageRoot, storyFile)}, ${path.relative(packageRoot, testFile)}`);
