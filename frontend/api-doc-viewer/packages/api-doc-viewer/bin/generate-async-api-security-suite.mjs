/**
 * Generates the AsyncAPI Security suites from `bin/async-api-security-case-definitions.mjs`:
 *
 * - plain fixtures + catalogue: `packages/samples/async-api/security/<case>/document.yaml`;
 * - diff fixtures + catalogue: `packages/samples/async-api-diffs/security/<case>/{before,after}.yaml`;
 * - stories: `src/stories/async-api-suite/security.stories.tsx`,
 *   `src/stories/async-api-diffs-suite/security.stories.tsx`;
 * - screenshot ITs: `src/it/async-api-suite/security.it-test.ts`,
 *   `src/it/async-api-diffs-suite/security.it-test.ts` (every case in display mode `detailed`, the
 *   default; server cases open the Channel section first). Display mode `simple` is covered by
 *   `Async API Suite (Display Mode = simple)` / `Async API Diffs Suite (Display Mode = simple)`.
 *
 * Usage (from packages/api-doc-viewer): node bin/generate-async-api-security-suite.mjs
 * Design: docs/design/async-api/features/security.md
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { stringify } from "yaml";
import { createBase, DIFF_CASES, PLAIN_CASES } from "./async-api-security-case-definitions.mjs";
import { toStorybookMetaId, toStorybookStorySlug } from "./storybook-story-id-utils.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(__dirname, "..");
const plainSamplesDir = path.resolve(packageRoot, "../samples/async-api/security");
const diffSamplesDir = path.resolve(packageRoot, "../samples/async-api-diffs/security");
const plainStoriesFile = path.resolve(packageRoot, "src/stories/async-api-suite/security.stories.tsx");
const diffStoriesFile = path.resolve(packageRoot, "src/stories/async-api-diffs-suite/security.stories.tsx");
const plainTestsFile = path.resolve(packageRoot, "src/it/async-api-suite/security.it-test.ts");
const diffTestsFile = path.resolve(packageRoot, "src/it/async-api-diffs-suite/security.it-test.ts");

const PLAIN_TITLE = "Async API Suite/Security";
const DIFF_TITLE = "Async API Diffs Suite/Security Samples";
const GENERATED = "Generated by bin/generate-async-api-security-suite.mjs - do not edit by hand.";

const toExportName = (caseId) => `Case_${caseId.replace(/[^A-Za-z0-9]/g, "_")}`;
const escapeCell = (text) => text.replaceAll("|", "\\|");

const build = (mutator) => {
  const document = createBase();
  mutator?.(document);
  return document;
};

function writeYaml(file, document) {
  fs.writeFileSync(file, stringify(document, { lineWidth: 0 }), "utf8");
}

function resetDir(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
}

const sectionNote = (section) => (section === "server" ? "Channel section, server block" : "message root (operation)");

function writePlainSamples() {
  resetDir(plainSamplesDir);
  for (const [caseId, , mutator] of PLAIN_CASES) {
    const dir = path.join(plainSamplesDir, caseId);
    fs.mkdirSync(dir, { recursive: true });
    writeYaml(path.join(dir, "document.yaml"), build(mutator));
  }
  const rows = PLAIN_CASES.map(([caseId, title, , section]) => `| \`${caseId}\` | ${escapeCell(title)} | ${sectionNote(section)} |`);
  fs.writeFileSync(path.join(plainSamplesDir, "README.md"), `# AsyncAPI plain fixtures — Security

One AsyncAPI 3.0 document per case (\`<case-id>/document.yaml\`): \`sendOperation\` / \`TestMessage\`
on \`testChannel\`, served by \`server0\`, with operation and / or server security. Design:
[docs/design/async-api/features/security.md](../../../../docs/design/async-api/features/security.md).

${GENERATED.replace("Generated by ", "Generated by `node ").replace(" - do not", "` (packages/api-doc-viewer) - do not")}

## Cases

| Case | Covers | Shown in |
| --- | --- | --- |
${rows.join("\n")}

## Storybook and screenshot tests

Storybook: \`${PLAIN_TITLE}\`, story \`Case_<case id>\` (\`src/stories/async-api-suite/security.stories.tsx\`).
ITs: \`src/it/async-api-suite/security.it-test.ts\`, every case in display mode \`detailed\`; server
cases open the Channel section first.
`, "utf8");
}

function writeDiffSamples() {
  resetDir(diffSamplesDir);
  for (const [caseId, , before, after] of DIFF_CASES) {
    const dir = path.join(diffSamplesDir, caseId);
    fs.mkdirSync(dir, { recursive: true });
    writeYaml(path.join(dir, "before.yaml"), build(before));
    writeYaml(path.join(dir, "after.yaml"), build(after));
  }
  const rows = DIFF_CASES.map(([caseId, title, , , section]) => `| \`${caseId}\` | ${escapeCell(title)} | ${sectionNote(section)} |`);
  fs.writeFileSync(path.join(diffSamplesDir, "README.md"), `# AsyncAPI diff fixtures — Security

Before / after AsyncAPI 3.0 documents (\`<case-id>/{before,after}.yaml\`) for the operation (\`1.*\`) and
server (\`2.*\`) Security sections. Design:
[docs/design/async-api/features/security.md](../../../../docs/design/async-api/features/security.md).

${GENERATED.replace("Generated by ", "Generated by `node ").replace(" - do not", "` (packages/api-doc-viewer) - do not")}

## Cases

| Case | Change | Shown in |
| --- | --- | --- |
${rows.join("\n")}

## Storybook and screenshot tests

Storybook: \`${DIFF_TITLE}\`, story \`Case_<case id>\` (\`src/stories/async-api-diffs-suite/security.stories.tsx\`).
ITs: \`src/it/async-api-diffs-suite/security.it-test.ts\`, every case in display mode \`detailed\`;
server cases open the Channel section first.
`, "utf8");
}

function writePlainStories() {
  const exports = PLAIN_CASES.map(([caseId]) => `export const ${toExportName(caseId)}: Story = createCaseStory("${caseId}");`);
  fs.writeFileSync(plainStoriesFile, `// ${GENERATED}
import type { Meta, StoryObj } from "@storybook/react-vite";
import {
  ASYNC_API_SECURITY_STORY_ARG_TYPES,
  ASYNC_API_SECURITY_STORY_DEFAULT_ARGS,
  AsyncApiSecuritySampleStory,
} from "./AsyncApiSecuritySampleStory";

const documents = import.meta.glob(
  "../../../../samples/async-api/security/*/document.yaml",
  { query: "?raw", import: "default", eager: true },
) as Record<string, string>;

const documentByCaseId: Record<string, string> = Object.fromEntries(
  Object.entries(documents).map(([file, yaml]) => [file.split("/").at(-2) ?? file, yaml]),
);

// eslint-disable-next-line storybook/story-exports
const meta = {
  title: "${PLAIN_TITLE}",
  component: AsyncApiSecuritySampleStory,
  argTypes: ASYNC_API_SECURITY_STORY_ARG_TYPES,
  args: ASYNC_API_SECURITY_STORY_DEFAULT_ARGS,
} satisfies Meta<typeof AsyncApiSecuritySampleStory>;

export default meta;

type Story = StoryObj<typeof meta>;

const createCaseStory = (caseId: string): Story => {
  const yaml = documentByCaseId[caseId];
  if (!yaml) {
    throw new Error(\`Sample case not found: \${caseId}\`);
  }
  return { name: caseId, args: { caseId, yaml } };
};

${exports.join("\n")}
`, "utf8");
}

function writeDiffStories() {
  const exports = DIFF_CASES.map(([caseId]) => `export const ${toExportName(caseId)}: Story = createCaseStory("${caseId}");`);
  fs.writeFileSync(diffStoriesFile, `// ${GENERATED}
import type { Meta, StoryObj } from "@storybook/react-vite";
import { ASYNC_API_SECURITY_STORY_ARG_TYPES, ASYNC_API_SECURITY_STORY_DEFAULT_ARGS } from "../async-api-suite/AsyncApiSecuritySampleStory";
import { collectSampleCases } from "../utils/diffs-samples-cases";
import { createSampleById } from "../utils/sample-cases";
import { AsyncApiSecurityDiffSampleStory } from "./AsyncApiSecurityDiffSampleStory";

const beforeFiles = import.meta.glob(
  "../../../../samples/async-api-diffs/security/*/before.yaml",
  { query: "?raw", import: "default", eager: true },
) as Record<string, string>;

const afterFiles = import.meta.glob(
  "../../../../samples/async-api-diffs/security/*/after.yaml",
  { query: "?raw", import: "default", eager: true },
) as Record<string, string>;

const sampleById = createSampleById(collectSampleCases(beforeFiles, afterFiles));

// eslint-disable-next-line storybook/story-exports
const meta = {
  title: "${DIFF_TITLE}",
  component: AsyncApiSecurityDiffSampleStory,
  argTypes: ASYNC_API_SECURITY_STORY_ARG_TYPES,
  args: ASYNC_API_SECURITY_STORY_DEFAULT_ARGS,
} satisfies Meta<typeof AsyncApiSecurityDiffSampleStory>;

export default meta;

type Story = StoryObj<typeof meta>;

const createCaseStory = (caseId: string): Story => {
  const sample = sampleById[caseId];
  if (!sample) {
    throw new Error(\`Sample case not found: \${caseId}\`);
  }
  return { name: caseId, args: { caseId, beforeYaml: sample.beforeYaml, afterYaml: sample.afterYaml } };
};

${exports.join("\n")}
`, "utf8");
}

function writeTests(file, title, cases, suiteName) {
  const metaId = toStorybookMetaId(title);
  const rows = cases.map(([caseId, , , , section]) => {
    const storyId = `${metaId}--${toStorybookStorySlug(toExportName(caseId))}`;
    return `  ['${caseId}', '${storyId}', ${(section ?? "operation") === "server"}],`;
  });
  fs.writeFileSync(file, `// ${GENERATED}
/**
 * Screenshot tests for ${suiteName}: every case in display mode \`detailed\` (the default). Server
 * cases open the Channel section first.
 */
import { storyPage } from '../service/storybook-service'
import { waitForRenderingComplete } from '../service/viewer-waits'

/** [case id, story id, open the Channel section (server security)]. */
const CASES: ReadonlyArray<readonly [string, string, boolean]> = [
${rows.join("\n")}
]

describe('${suiteName}', () => {
  beforeEach(async () => {
    await jestPuppeteer.resetPage()
  })

  it.each(CASES)('%s', async (_caseId, storyId, openChannel) => {
    const story = await storyPage(page, storyId)
    const component = await story.viewComponent()
    await waitForRenderingComplete(page)
    if (openChannel) {
      await page.click('[data-testid="message-channel"]')
      await page.waitForSelector('[data-testid="message-channel-section"]', { visible: true })
      await waitForRenderingComplete(page)
    }
    expect(await component.captureScreenshot()).toMatchImageSnapshot()
  })
})
`, "utf8");
}

function main() {
  writePlainSamples();
  writeDiffSamples();
  writePlainStories();
  writeDiffStories();
  // Plain rows are [id, title, mutator, section]: align to the diff tuple shape (section last).
  writeTests(plainTestsFile, PLAIN_TITLE, PLAIN_CASES.map(([id, title, mutator, section]) => [id, title, mutator, undefined, section]), "Async API Suite - Security");
  writeTests(diffTestsFile, DIFF_TITLE, DIFF_CASES, "Async API Diffs Suite - Security Samples");
  console.log(`AsyncAPI security suites: ${PLAIN_CASES.length} plain cases, ${DIFF_CASES.length} diff cases.`);
}

main();
