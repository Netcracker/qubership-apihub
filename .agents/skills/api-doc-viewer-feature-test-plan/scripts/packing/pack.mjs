// Packs the fixtures of api-doc-viewer into the test-data packages of a QA plan. An OpenAPI package packs many
// fixture cases into a few documents: each case becomes its operations under the path prefix "/<code>-<case>". A
// "files" package keeps one document per case; a "versions" package copies samples as they are. The packages are
// defined in the plan's config/test-plan.config.mjs. Usage, from the repository root, after `pnpm install` and
// `pnpm exec nx run-many -t build -p api-diff compatibility-suites ddlapi`:
//
//   node .agents/skills/api-doc-viewer-feature-test-plan/scripts/packing/pack.mjs --qa qa-<feature>
//
// Writes qa-<feature>/samples/packages/: one folder per package with its version folders, a README.md per package
// that lists its cases, and manifest.json with every case. The output folder is deleted and written again on every
// run; the output is deterministic.
import fs from 'node:fs'
import path from 'node:path'
import {
  HTTP_METHODS,
  OUTPUT_ROOT,
  QA_ROOT,
  VERSIONS,
  YAML,
  caseFileContent,
  isObject,
  loadConfig,
  packageCases,
  stableStringify,
} from './lib.mjs'
import { findBaseline } from './baselines.mjs'
import { loadFormats } from './formats/index.mjs'

const { packages: PACKAGES } = await loadConfig()
const FORMATS = await loadFormats()
const GENERATED_BY = 'Generated by the `api-doc-viewer-feature-test-plan` skill (`scripts/packing/pack.mjs`)'

// Root keys that every case of a document shares; the other root keys are compared (see rootSignature).
const MERGED_ROOT_KEYS = new Set(['openapi', 'info', 'paths', 'components'])

const escapePointer = token => token.replace(/~/g, '~0').replace(/\//g, '~1')

// ----- What a case needs from its document -----

// The root keys other than openapi, info, paths, and components (servers, security, tags, x-…), and the OAS
// version: two cases share a document only when these are equal on every side.
// A case that adds or removes the whole components object also stays apart from cases that keep theirs: apiDiff
// classifies the removal of the whole object differently from the removal of the component inside it.
function rootSignature(sides) {
  const roots = sides.map(document => Object.fromEntries(
    Object.entries(document).filter(([key]) => !MERGED_ROOT_KEYS.has(key) || key === 'openapi')))
  const components = sides.map(document => document.components !== undefined)
  return stableStringify(components.every(present => present === components[0]) ? roots : [roots, components])
}

// Component keys ("schemas/Order", "securitySchemes/ApiKey") a document defines or uses. A security requirement
// names a scheme without a $ref, and a case may name a scheme it does not define (an unresolved scheme): both
// count, so that no other case of the document defines that name.
function componentKeys(document) {
  const keys = new Set()
  for (const [section, entries] of Object.entries(document.components ?? {})) {
    for (const name of Object.keys(entries ?? {})) keys.add(`${section}/${name}`)
  }
  const visit = (value, parentKey) => {
    if (Array.isArray(value)) {
      if (parentKey === 'security') {
        for (const requirement of value) {
          for (const name of Object.keys(requirement ?? {})) keys.add(`securitySchemes/${name}`)
        }
      }
      value.forEach(item => visit(item))
    } else if (isObject(value)) {
      for (const [key, child] of Object.entries(value)) {
        if (key === '$ref' && typeof child === 'string' && child.startsWith('#/components/')) {
          const [section, name] = child.slice('#/components/'.length).split('/')
          if (section && name) keys.add(`${section}/${name.replace(/~1/g, '/').replace(/~0/g, '~')}`)
        } else {
          visit(child, key)
        }
      }
    }
  }
  visit(document)
  return keys
}

function componentValue(document, key) {
  const slash = key.indexOf('/')
  return document.components?.[key.slice(0, slash)]?.[key.slice(slash + 1)]
}

// ----- Packing -----

// A case fits a document when the root keys are equal and every component key that both use has the same value on
// each side (a key that one side lacks must be absent on that side of the document too).
function fits(document, item) {
  if (document.signature !== item.signature) return false
  for (const key of item.keys) {
    if (!document.keys.has(key)) continue
    for (let side = 0; side < item.sides.length; side++) {
      const a = componentValue(document.sides[side], key)
      const b = componentValue(item.sides[side], key)
      if (stableStringify(a) !== stableStringify(b)) return false
    }
  }
  return true
}

function prefixedPaths(paths, prefix) {
  return Object.fromEntries(Object.entries(paths ?? {}).map(([p, item]) => [`/${prefix}${p}`, item]))
}

// A $ref into "#/paths/…" points at the old path key; rewrite it to the prefixed key.
function rewritePathRefs(value, prefix) {
  if (Array.isArray(value)) return value.map(item => rewritePathRefs(item, prefix))
  if (!isObject(value)) return value
  return Object.fromEntries(Object.entries(value).map(([key, child]) => {
    if (key === '$ref' && typeof child === 'string' && child.startsWith('#/paths/')) {
      const [oldKey, ...rest] = child.slice('#/paths/'.length).split('/')
      const newKey = escapePointer(`/${prefix}${oldKey.replace(/~1/g, '/').replace(/~0/g, '~')}`)
      return [key, ['#/paths', newKey, ...rest].join('/')]
    }
    return [key, rewritePathRefs(child, prefix)]
  }))
}

function addCase(document, item) {
  document.cases.push(item)
  for (const key of item.keys) document.keys.add(key)
  item.sides.forEach((source, side) => {
    const target = document.sides[side]
    const prefixed = rewritePathRefs(source, item.id)
    for (const [p, pathItem] of Object.entries(prefixedPaths(prefixed.paths, item.id))) {
      if (p in target.paths) throw new Error(`${item.id}: path ${p} is already in the document`)
      target.paths[p] = pathItem
    }
    for (const [section, entries] of Object.entries(prefixed.components ?? {})) {
      target.components ??= {}
      target.components[section] ??= {}
      Object.assign(target.components[section], entries)
    }
    for (const [key, value] of Object.entries(prefixed)) {
      if (!MERGED_ROOT_KEYS.has(key)) target[key] = value
    }
  })
}

function emptyDocument(packageName, index, item) {
  return {
    signature: item.signature,
    keys: new Set(),
    cases: [],
    sides: item.sides.map(source => ({
      openapi: source.openapi,
      info: { title: `${packageName} document ${index}`, version: '1.0.0' },
      paths: {},
    })),
  }
}

function pack(packageName, cases) {
  const documents = []
  for (const item of cases) {
    item.signature = rootSignature(item.sides)
    item.keys = new Set(item.sides.flatMap(side => [...componentKeys(side)]))
    let document = documents.find(candidate => fits(candidate, item))
    if (!document) {
      document = emptyDocument(packageName, documents.length + 1, item)
      documents.push(document)
    }
    addCase(document, item)
  }
  return documents
}

// ----- Output -----

// Root keys in the usual order, components last; the YAML keeps every shared object written out in full.
function serialize(document) {
  const { openapi, info, ...rest } = document
  const { paths, components, ...other } = rest
  const ordered = { openapi, info, ...other, paths, ...(components ? { components } : {}) }
  return YAML.stringify(ordered, { lineWidth: 0, aliasDuplicateObjects: false })
}

function operationsOf(document) {
  return Object.entries(document.paths ?? {}).flatMap(([p, item]) =>
    Object.keys(item ?? {}).filter(k => HTTP_METHODS.has(k)).map(method => `${method.toUpperCase()} ${p}`))
}

// What QA looks for in the portal: what the document's format names (formats/), or the operations of an OpenAPI
// document.
function entriesOf(content, item) {
  const format = FORMATS.find(candidate => candidate.matches(content, item))
  if (format) return format.lookFor(content)
  return typeof content === 'string' ? [] : operationsOf(content ?? {})
}

function writeFilesPackage(definition) {
  const { layout } = definition
  const cases = packageCases(definition)
  const versions = VERSIONS[layout]
  const packageDir = path.join(OUTPUT_ROOT, definition.name)
  const manifest = cases.map(item => {
    const fileName = `${item.id}.${item.extension}`
    versions.forEach((version, side) => {
      fs.mkdirSync(path.join(packageDir, version), { recursive: true })
      fs.writeFileSync(path.join(packageDir, version, fileName), caseFileContent(item, side))
    })
    return {
      id: item.id,
      package: definition.name,
      layout,
      document: fileName,
      fixture: item.fixture,
      baseline: findBaseline(item.baselineHint ?? item.fixture),
      ...(item.title ? { title: item.title } : {}),
      operations: [...new Set(item.sides.flatMap(side => entriesOf(side, item)))],
    }
  })
  fs.writeFileSync(path.join(packageDir, 'README.md'), packageReadme(definition, layout, cases, manifest))
  return { definition, layout, documents: cases, manifest }
}

// A package of copied samples (copied-packages.mjs): each version is a folder, the files are copied byte for byte.
function writeVersionsPackage(definition) {
  const packageDir = path.join(OUTPUT_ROOT, definition.name)
  for (const version of definition.versions) {
    fs.mkdirSync(path.join(packageDir, version.name), { recursive: true })
    for (const file of version.files) {
      fs.copyFileSync(path.join(QA_ROOT, file.from), path.join(packageDir, version.name, file.as))
    }
  }
  const items = [...new Set(definition.versions.map(version => version.item))]
  const manifest = items.map(item => {
    const versions = definition.versions.filter(version => version.item === item)
    return {
      id: `${definition.name.toLowerCase()}-${item}`,
      package: definition.name,
      layout: versions.length > 1 ? 'diffs' : 'plain',
      document: versions[0].files.map(file => file.as).join(', '),
      fixture: versions.flatMap(version => version.files.map(file => file.from)).join(' -> '),
      versions: versions.map(version => version.name),
      operations: [],
    }
  })
  const several = items.length > 1
  const publish = several
    ? 'Publish each folder as a version of the same name. A version ending in `2.0` has the `1.0` version of the ' +
      'same item as its previous version: compare it with that version.'
    : definition.versions.length > 1
      ? 'Publish `1.0/` as version `1.0`, then `2.0/` as version `2.0` with `1.0` as the previous version. ' +
        'Compare `2.0` with `1.0`.'
      : 'Publish `1.0/` as version `1.0`.'
  const lines = [
    `# ${definition.name}`,
    '',
    ...wrap(`${definition.description}. Cases: ${definition.cases.join(', ')}. ${GENERATED_BY} from copied ` +
      'samples; do not edit by hand.'),
    '',
    ...wrap(`${publish} The files are the samples as they are; only their names change, so that a document ` +
      'keeps one name across versions.'),
    '',
    '| Version | Previous version | Document | Copied from |',
    '| --- | --- | --- | --- |',
    ...definition.versions.map(version => `| \`${version.name}\` | ` +
      `${version.previous ? `\`${version.previous}\`` : ''} | ` +
      `${version.files.map(file => `\`${file.as}\``).join('<br>')} | ` +
      `${version.files.map(file => `\`${file.from}\``).join('<br>')} |`),
    '',
  ]
  fs.writeFileSync(path.join(packageDir, 'README.md'), lines.join('\n'))
  const versionsLabel = several
    ? `${definition.versions.length} versions`
    : definition.versions.map(version => version.name).join(', ')
  const documents = definition.versions.flatMap(version => version.files)
  return { definition, layout: definition.versions.length > 1 ? 'diffs' : 'plain', documents, manifest, versionsLabel }
}

function writePackage(definition) {
  if (definition.format === 'versions') return writeVersionsPackage(definition)
  if (definition.format === 'files') return writeFilesPackage(definition)
  const { layout } = definition
  const cases = packageCases(definition)
  const versions = VERSIONS[layout]
  const documents = pack(definition.name, cases)
  const packageDir = path.join(OUTPUT_ROOT, definition.name)
  const manifest = []
  documents.forEach((document, index) => {
    const fileName = `${definition.name.toLowerCase()}-${index + 1}.yaml`
    versions.forEach((version, side) => {
      fs.mkdirSync(path.join(packageDir, version), { recursive: true })
      fs.writeFileSync(path.join(packageDir, version, fileName), serialize(document.sides[side]))
    })
    for (const item of document.cases) {
      const prefixed = item.sides.map(side => prefixedPaths(side.paths, item.id))
      manifest.push({
        id: item.id,
        package: definition.name,
        layout,
        document: fileName,
        fixture: item.fixture,
        baseline: findBaseline(item.baselineHint ?? item.fixture),
        ...(item.title ? { title: item.title } : {}),
        ...(item.marker ? { marker: true } : {}),
        ...(item.members ? { members: membersOf(item) } : {}),
        operations: [...new Set(prefixed.flatMap(paths => operationsOf({ paths })))],
      })
    }
  })
  // List the cases in the order of their sources, not grouped by document.
  const order = new Map(cases.map((item, index) => [item.id, index]))
  manifest.sort((a, b) => order.get(a.id) - order.get(b.id))
  fs.writeFileSync(path.join(packageDir, 'README.md'), packageReadme(definition, layout, documents, manifest))
  return { definition, layout, documents, manifest }
}

// The member cases of a composite case (builders/composite.mjs), each with its fixture and baseline.
function membersOf(item) {
  return item.members.map(member => ({
    id: member.id,
    fixture: member.fixture,
    baseline: findBaseline(member.baselineHint ?? member.fixture),
  }))
}

// The member table of a package with composite cases: which fixture each renamed name comes from.
function membersSection(manifest) {
  const composites = manifest.filter(c => c.members)
  if (!composites.length) return []
  return [
    '## Composite cases',
    '',
    ...wrap('A composite case is one operation that merges the operations of several fixture cases. A name that ' +
      'another member already uses with a different value carries the member\'s case ID: a parameter ' +
      '`status_dqp-07`, a header `X-Rate-Limit_drh-03`, a media type `application/vnd.drb-02+json`, a component ' +
      '`Order_dsec-11`, or, in a merged JSON Schema, the property `jstr-01`. A name without a suffix comes from ' +
      'the first member that uses it. Compare each member with its baseline: the content, not the layout.'),
    '',
    '| Case | Member | Fixture | Baseline |',
    '| --- | --- | --- | --- |',
    ...composites.flatMap(c => c.members.map(m =>
      `| \`${c.id}\` | \`${m.id}\` | \`${m.fixture}\` | ${m.baseline ? `\`${m.baseline.split('/').pop()}\`` : ''} |`)),
    '',
  ]
}

// Wraps prose at 120 characters, the line length of the Markdown in this repository.
function wrap(text, width = 120) {
  const lines = []
  let line = ''
  for (const word of text.split(/\s+/)) {
    if (line && line.length + 1 + word.length > width) {
      lines.push(line)
      line = word
    } else {
      line = line ? `${line} ${word}` : word
    }
  }
  if (line) lines.push(line)
  return lines
}

function packageReadme(definition, layout, documents, manifest) {
  const publish = layout === 'plain'
    ? 'Publish the files of `1.0/` as version `1.0` of the package.'
    : 'Publish the files of `1.0/` as version `1.0`, then the files of `2.0/` as version `2.0` with `1.0` as the ' +
      'previous version. Compare `2.0` with `1.0`.'
  const example = manifest[0].id
  const findCase = definition.format === 'files'
    ? `${publish} The package holds ${manifest.length} cases, one document each: case \`${example}\` is the ` +
      `document \`${manifest[0].document}\`. The names that APIHUB builds its IDs from carry the case ID, so ` +
      'that the documents of one version do not clash: AsyncAPI operation keys, DDL schema names, GraphQL root ' +
      'fields. The "Look for" column lists them.'
    : `${publish} The package holds ${manifest.length} cases in ${documents.length} documents. Find a case by its ` +
      `path prefix in the operation list: case \`${example}\` is every operation whose path starts with ` +
      `\`/${example}/\`. Cases keep their \`operationId\` values, so a document may repeat one; APIHUB builds the ` +
      'operation IDs from the path and the method, so the repeats do not affect the publication.'
  const operationsHeader = definition.format === 'files' ? 'Look for' : 'Operations'
  const hasTitles = manifest.some(c => c.title)
  const lines = [
    `# ${definition.name}`,
    '',
    ...wrap(`${definition.description}. ${GENERATED_BY}; do not edit by hand.`),
    '',
    ...wrap(findCase),
    '',
    ...(manifest.some(c => c.marker)
      ? [...wrap('A case marked "(marker)" has no change that apiDiff reports, and a version comparison lists only ' +
        'changed operations. In version `2.0` its operation gets a description that starts with "QA marker", so ' +
        'that the comparison lists it; the rest of the operation is as the source has it.'), '']
      : []),
    // Cases built in code carry the title of their story case.
    ...(hasTitles
      ? [`| Case | Title | ${operationsHeader} | Document | Fixture |`, '| --- | --- | --- | --- | --- |']
      : [`| Case | ${operationsHeader} | Document | Fixture |`, '| --- | --- | --- | --- |']),
    ...manifest.map(c => `| \`${c.id}\`${c.marker ? ' (marker)' : ''} | ` +
      `${hasTitles ? `${(c.title ?? '').replace(/\|/g, '\\|')} | ` : ''}` +
      `${c.operations.map(o => `\`${o}\``).join('<br>')} | \`${c.document}\` | ` +
      `${c.fixture.startsWith('new') || c.members ? c.fixture : `\`${c.fixture}\``} |`),
    '',
    ...membersSection(manifest),
  ]
  return lines.join('\n')
}

function indexReadme(results) {
  const lines = [
    '# Test-data packages',
    '',
    ...wrap(`${GENERATED_BY} from the fixtures in \`frontend/api-doc-viewer/packages/samples/\` and from the ` +
      'samples copied into `samples/`; do not edit by hand.'),
    '`manifest.json` lists every case with its operations, document, and fixture. Fixture paths are relative to',
    '`frontend/api-doc-viewer/packages/samples/`, or to this directory\'s parent for the copied samples.',
    '',
    '| Package | Layout | Versions | Cases | Documents |',
    '| --- | --- | --- | ---: | ---: |',
    ...results.map(r => `| [${r.definition.name}](${r.definition.name}/README.md) | ${r.layout} | ` +
      `${r.versionsLabel ?? VERSIONS[r.layout].join(', ')} | ${r.manifest.length} | ` +
      `${r.documents.length} |`),
    `| **Total** | | | **${results.reduce((n, r) => n + r.manifest.length, 0)}** | ` +
      `**${results.reduce((n, r) => n + r.documents.length, 0)}** |`,
    '',
  ]
  return lines.join('\n')
}

fs.rmSync(OUTPUT_ROOT, { recursive: true, force: true })
fs.mkdirSync(OUTPUT_ROOT, { recursive: true })
const results = PACKAGES.map(writePackage)
fs.writeFileSync(path.join(OUTPUT_ROOT, 'README.md'), indexReadme(results))
fs.writeFileSync(path.join(OUTPUT_ROOT, 'manifest.json'),
  JSON.stringify(results.flatMap(r => r.manifest), null, 2) + '\n')
for (const r of results) {
  console.log(`${r.definition.name}: ${r.manifest.length} cases, ${r.documents.length} documents`)
}
